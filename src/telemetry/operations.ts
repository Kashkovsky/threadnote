/** Resolve only registered command words; positionals and option values are never appended. */
export function cliAnonymousTelemetryOperation(
  topLevel: string,
  subcommand: string | undefined,
  nestedSubcommand: string | undefined,
): string {
  const knownSubcommands = CLI_SUBCOMMANDS[topLevel as keyof typeof CLI_SUBCOMMANDS] as readonly string[] | undefined;
  if (knownSubcommands === undefined || subcommand === undefined || !knownSubcommands.includes(subcommand)) {
    return safeAnonymousTelemetryOperation(topLevel);
  }
  const nested = `${topLevel}.${subcommand}.${nestedSubcommand ?? ''}`;
  if (ANONYMOUS_TELEMETRY_OPERATIONS.has(nested)) return nested;
  return safeAnonymousTelemetryOperation(`${topLevel}.${subcommand}`);
}

/** Final outbound operation allowlist. */
export function safeAnonymousTelemetryOperation(value: string): string {
  return ANONYMOUS_TELEMETRY_OPERATIONS.has(value) ? value : 'unknown';
}
