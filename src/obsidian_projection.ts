const PROJECTION_NOTE_FILE_MODE = 0o644;
const PROJECTION_LOCK_RETRY_MILLISECONDS = 25;
const PROJECTION_LOCK_STALE_MILLISECONDS = 5 * 60 * 1_000;
const PROJECTION_LOCK_WAIT_MILLISECONDS = 10_000;
const PROJECTION_LOCK_OPTIONS = {
  retryIntervalMilliseconds: PROJECTION_LOCK_RETRY_MILLISECONDS,
  staleAfterMilliseconds: PROJECTION_LOCK_STALE_MILLISECONDS,
  waitTimeoutMilliseconds: PROJECTION_LOCK_WAIT_MILLISECONDS,
} as const;
