export const runObsidianProjectionSync = Effect.fn('obsidian.projectionSync')(function* (
  config: RuntimeConfig,
  options: ObsidianProjectionCommandOptions,
) {
  const apply = options.apply === true && options.dryRun !== true;
  const projection = requireObsidianProjection(yield* readObsidianConfiguration(config), options.id);
  if (!projection.enabled) {
    return yield* Effect.fail(new Error(`Obsidian projection "${projection.id}" is disabled.`));
  }
  const fs = yield* FileSystem.FileSystem;
  const root = yield* projectionRoot(projection);
  const statePath = yield* projectionStatePath(projection);
  return yield* withExclusiveFileLock(
    fs,
    `${statePath}.lock`,
    PROJECTION_LOCK_OPTIONS,
    Effect.gen(function* () {
      const plan = yield* buildProjectionPlan(config, projection);
      yield* printProjectionPlan(plan);
      if (!apply) {
        yield* Console.log('Dry run complete. Re-run with --apply to update the projection.');
        return plan.entries;
      }
      const nextFiles: Record<string, ObsidianProjectionFileState> = {...plan.state.files};
      const mutableEntries = [...plan.entries];
      const writes = mutableEntries.filter(
        entry =>
          entry.action === 'add' ||
          entry.action === 'update' ||
          (entry.action === 'drift' && options.force === true && plan.desired.has(entry.relativePath)),
      );
      yield* Effect.forEach(
        writes,
        entry =>
          Effect.gen(function* () {
            const desired = plan.desired.get(entry.relativePath);
            if (!desired) {
              return;
            }
            yield* writeProjectionFile(root, desired);
            nextFiles[entry.relativePath] = {contentHash: desired.contentHash, uri: desired.uri};
          }),
        {concurrency: PROJECTION_WRITE_CONCURRENCY, discard: true},
      );
      for (const entry of mutableEntries.filter(item => item.action === 'unchanged')) {
        const desired = plan.desired.get(entry.relativePath);
        if (desired) {
          nextFiles[entry.relativePath] = {contentHash: desired.contentHash, uri: desired.uri};
        }
      }
      const removals = mutableEntries.filter(
        entry =>
          entry.action === 'remove' ||
          (entry.action === 'drift' && options.force === true && !plan.desired.has(entry.relativePath)),
      );
      for (const entry of removals) {
        const target = yield* safeProjectionTarget(root, entry.relativePath);
        yield* fs.remove(target, {force: true});
        delete nextFiles[entry.relativePath];
      }
      const currentTimeMillis = yield* Clock.currentTimeMillis;
      const nextState: ObsidianProjectionState = {
        files: nextFiles,
        projectionId: projection.id,
        syncedAt: new Date(currentTimeMillis).toISOString(),
        version: PROJECTION_STATE_VERSION,
      };
      yield* writeProjectionState(statePath, nextState);
      const counts = projectionCounts(mutableEntries);
      yield* Console.log(
        `Projection sync complete: ${counts.add} added, ${counts.update} updated, ${counts.remove} removed, ` +
          `${counts.unchanged} unchanged, ${counts.drift} drift, ${counts.skip} skipped.`,
      );
      return mutableEntries;
    }),
  );
});

export const runObsidianProjectionPublish = Effect.fn('obsidian.projectionPublish')(function* (
  config: RuntimeConfig,
  options: ObsidianProjectionPublishOptions,
) {
  const apply = options.apply === true && options.dryRun !== true;
  const configuration = yield* readObsidianConfiguration(config);
  const projection = requireObsidianProjection(configuration, options.id);
  if (!projection.enabled) {
    return yield* Effect.fail(new Error(`Obsidian projection "${projection.id}" is disabled.`));
  }
  if (projection.selectedUris === undefined) {
    return yield* Effect.fail(
      new Error(
        `Obsidian projection "${projection.id}" predates explicit memory selection. ` +
          'Re-run threadnote projection add with the same id, vault, and folder plus --apply, then publish again.',
      ),
    );
  }
  const requestedUris = normalizeProjectionMemoryUris(config, options.uris);
  const selectedUris = [...new Set([...projection.selectedUris, ...requestedUris])].sort((left, right) =>
    left.localeCompare(right),
  );
  const nextProjection = {...projection, selectedUris};
  const plan = yield* buildProjectionPlan(config, nextProjection);
  const projectedUris = new Set([...plan.desired.values()].flatMap(file => (file.uri === undefined ? [] : [file.uri])));
  const unavailable = requestedUris.filter(uri => !projectedUris.has(uri));
  if (unavailable.length > 0) {
    return yield* Effect.fail(
      new Error(
        `Cannot publish ${unavailable.join(', ')}. Ensure each memory exists and matches projection ` +
          `"${projection.id}" kind, status, and shared-memory filters.`,
      ),
    );
  }
  const addedSelectionCount = selectedUris.length - projection.selectedUris.length;
  yield* Console.log(
    `${apply ? 'Publishing' : 'Would publish'} ${requestedUris.length} selected memory URI(s) to ` +
      `Obsidian projection "${projection.id}" (${addedSelectionCount} newly selected).`,
  );
  if (!apply) {
    yield* printProjectionPlan(plan);
    yield* Console.log('Dry run complete. Re-run with --apply to write the selected memories to the vault.');
    return plan.entries;
  }
  yield* writeObsidianConfiguration(config, upsertObsidianProjection(configuration, nextProjection));
  return yield* runObsidianProjectionSync(config, {
    apply: true,
    force: options.force,
    id: projection.id,
  });
});

export const runObsidianProjectionRemove = Effect.fn('obsidian.projectionRemove')(function* (
  config: RuntimeConfig,
  options: ObsidianProjectionCommandOptions,
) {
  const apply = options.apply === true && options.dryRun !== true;
  const configuration = yield* readObsidianConfiguration(config);
  const projection = requireObsidianProjection(configuration, options.id);
  const plan = yield* buildProjectionPlan(config, projection, {empty: true});
  yield* printProjectionPlan(plan);
  const drift = plan.entries.filter(entry => entry.action === 'drift');
  if (!apply) {
    yield* Console.log('Would remove unchanged managed projection files and preserve the vault and memories.');
    yield* Console.log('Re-run with --apply to continue.');
    return;
  }
  if (drift.length > 0 && options.force !== true) {
    return yield* Effect.fail(
      new Error(
        `Projection "${projection.id}" contains ${drift.length} edited managed file(s). ` +
          'Resolve them or repeat with --force to remove the managed files.',
      ),
    );
  }
  const fs = yield* FileSystem.FileSystem;
  const root = yield* projectionRoot(projection);
  const statePath = yield* projectionStatePath(projection);
  yield* withExclusiveFileLock(
    fs,
    `${statePath}.lock`,
    PROJECTION_LOCK_OPTIONS,
    Effect.gen(function* () {
      for (const entry of plan.entries.filter(item => item.action === 'remove' || item.action === 'drift')) {
        yield* fs.remove(yield* safeProjectionTarget(root, entry.relativePath), {force: true});
      }
      yield* fs.remove(statePath, {force: true});
      yield* writeObsidianConfiguration(config, removeObsidianProjection(configuration, projection.id));
      yield* removeEmptyProjectionDirectories(root);
    }),
  );
  yield* Console.log(`Removed Obsidian projection "${projection.id}". The vault and memories were preserved.`);
});

export const resolveProjectedMemoryPath = Effect.fn('obsidian.resolveProjectedMemoryPath')(function* (
  config: RuntimeConfig,
  uri: string,
  projectionId?: string,
) {
  const configuration = yield* readObsidianConfiguration(config);
  const projections = configuration.projections.filter(
    projection => projection.enabled && (projectionId === undefined || projection.id === projectionId),
  );
  const matches: Array<{path: string; projection: ObsidianProjectionConfig; relativePath: string}> = [];
  for (const projection of projections) {
    const state = yield* readProjectionState(yield* projectionStatePath(projection), projection.id);
    for (const [relativePath, entry] of Object.entries(state.files)) {
      if (entry.uri === uri) {
        const root = yield* projectionRoot(projection);
        matches.push({
          path: yield* safeProjectionTarget(root, relativePath),
          projection,
          relativePath,
        });
      }
    }
  }
  if (matches.length === 0) {
    return yield* Effect.fail(
      new Error(
        `Memory ${uri} is not present in an enabled Obsidian projection. ` +
          'Run threadnote projection publish <id> --uri <memory-uri> --apply.',
      ),
    );
  }
  if (matches.length > 1) {
    return yield* Effect.fail(
      new Error(
        `Memory ${uri} appears in multiple projections. Pass --projection with one of: ${matches
          .map(match => match.projection.id)
          .join(', ')}.`,
      ),
    );
  }
  return matches[0] as (typeof matches)[number];
});

const buildProjectionPlan = Effect.fn('obsidian.buildProjectionPlan')(function* (
  config: RuntimeConfig,
  projection: ObsidianProjectionConfig,
  options: {readonly empty?: boolean} = {},
) {
  const fs = yield* FileSystem.FileSystem;
  const root = yield* projectionRoot(projection);
  const state = yield* readProjectionState(yield* projectionStatePath(projection), projection.id);
  const records = options.empty === true ? [] : yield* readProjectionMemories(config, projection);
  const desired = options.empty === true ? new Map() : yield* desiredProjectionFiles(projection, records);
  const entries: ObsidianProjectionEntry[] = [];
  for (const [relativePath, file] of desired) {
    const target = yield* safeProjectionTarget(root, relativePath);
    const recorded = state.files[relativePath];
    const currentHash = yield* fileContentHash(fs, target);
    if (!recorded) {
      entries.push({
        action: currentHash === undefined ? 'add' : 'skip',
        detail: currentHash === undefined ? undefined : 'unmanaged file occupies the projected path',
        relativePath,
        uri: file.uri,
      });
      continue;
    }
    if (currentHash === undefined) {
      entries.push({action: 'add', detail: 'managed file is missing', relativePath, uri: file.uri});
    } else if (currentHash !== recorded.contentHash) {
      entries.push({action: 'drift', detail: 'managed file was edited', relativePath, uri: file.uri});
    } else if (currentHash === file.contentHash) {
      entries.push({action: 'unchanged', relativePath, uri: file.uri});
    } else {
      entries.push({action: 'update', relativePath, uri: file.uri});
    }
  }
  for (const [relativePath, recorded] of Object.entries(state.files)) {
    if (desired.has(relativePath)) {
      continue;
    }
    const target = yield* safeProjectionTarget(root, relativePath);
    const currentHash = yield* fileContentHash(fs, target);
    if (currentHash === undefined) {
      entries.push({action: 'remove', detail: 'state entry is already absent', relativePath, uri: recorded.uri});
    } else if (currentHash !== recorded.contentHash) {
      entries.push({action: 'drift', detail: 'orphaned managed file was edited', relativePath, uri: recorded.uri});
    } else {
      entries.push({action: 'remove', relativePath, uri: recorded.uri});
    }
  }
  entries.sort(
    (left, right) =>
      projectionActionRank(left.action) - projectionActionRank(right.action) ||
      left.relativePath.localeCompare(right.relativePath),
  );
  return {desired, entries, projection, state} satisfies ProjectionPlan;
});

const readProjectionMemories = Effect.fn('obsidian.readProjectionMemories')(function* (
  config: RuntimeConfig,
  projection: ObsidianProjectionConfig,
) {
  const store = yield* ResourceStore;
  const location = resourceStoreLocation(config);
  const selectedUris =
    projection.selectedUris ??
    (yield* store.list(location, `threadnote://user/${uriSegment(config.user)}/memories`, {recursive: true}).pipe(
      Effect.catchTag('ResourceNotFound', () => Effect.succeed([])),
      Effect.map(entries =>
        entries
          .filter(entry => entry.type === 'file' && entry.uri.toLowerCase().endsWith('.md'))
          .map(entry => entry.uri),
      ),
    ));
  const records = yield* Effect.forEach(
    selectedUris,
    uri =>
      Effect.gen(function* () {
        const content = yield* store
          .read(location, uri)
          .pipe(Effect.catchTag('ResourceNotFound', () => Effect.succeed(undefined)));
        if (content === undefined) {
          return undefined;
        }
        const record = parseMemoryDocument(uri, content);
        if (
          !record ||
          !projection.kinds.includes(record.metadata.kind) ||
          !projection.statuses.includes(record.metadata.status) ||
          (!projection.includeShared && isSharedMemoryUri(uri))
        ) {
          return undefined;
        }
        return record;
      }),
    {concurrency: MEMORY_READ_CONCURRENCY},
  );
  return records.filter((record): record is MemoryRecord => record !== undefined);
});

const desiredProjectionFiles = Effect.fn('obsidian.desiredProjectionFiles')(function* (
  projection: ObsidianProjectionConfig,
  records: readonly MemoryRecord[],
) {
  const identities = yield* Effect.forEach(
    records,
    record =>
      Effect.gen(function* () {
        const id = record.metadata.memoryId ?? `tn_${(yield* sha256Hex(record.uri)).slice(0, 20)}`;
        const relativePath = projectionMemoryPath(record, id);
        return {id, record, relativePath};
      }),
    {concurrency: MEMORY_READ_CONCURRENCY},
  );
  const projectedPathByUri = new Map(identities.map(item => [item.record.uri, item.relativePath]));
  const desired = new Map<string, DesiredProjectionFile>();
  for (const item of identities) {
    const rendered = yield* renderProjectionMemory(projection, item.record, item.id, projectedPathByUri);
    if (!rendered) {
      continue;
    }
    desired.set(item.relativePath, {
      content: rendered.content,
      contentHash: rendered.contentHash,
      relativePath: item.relativePath,
      uri: item.record.uri,
    });
  }
  for (const generated of yield* generatedProjectionFiles(projection)) {
    desired.set(generated.relativePath, generated);
  }
  return desired;
});

const renderProjectionMemory = Effect.fn('obsidian.renderProjectionMemory')(function* (
  projection: ObsidianProjectionConfig,
  record: MemoryRecord,
  memoryId: string,
  projectedPathByUri: ReadonlyMap<string, string>,
) {
  const canonical = canonicalMemoryDocumentContent(record.content);
  const sourceHash = record.metadata.sourceHash ?? `sha256:${yield* sha256Hex(canonical)}`;
  const visibility = record.metadata.visibility ?? (isSharedMemoryUri(record.uri) ? 'shared' : 'personal');
  const relations = memoryRelations(record);
  const frontmatter = {
    threadnote_schema: 1,
    threadnote_id: memoryId,
    threadnote_uri: record.uri,
    threadnote_generated: true,
    kind: record.metadata.kind,
    status: record.metadata.status,
    ...(record.metadata.project ? {project: record.metadata.project} : {}),
    ...(record.metadata.topic ? {topic: record.metadata.topic} : {}),
    visibility,
    authority: record.metadata.authority ?? (visibility === 'shared' ? 'reviewed_shared' : 'agent_generated'),
    trust: record.metadata.trust ?? (visibility === 'shared' ? 'approved' : 'inferred'),
    created_at: record.metadata.createdAt ?? record.metadata.timestamp,
    updated_at: record.metadata.updatedAt ?? record.metadata.timestamp,
    ...(record.metadata.validFrom ? {valid_from: record.metadata.validFrom} : {}),
    ...(record.metadata.validTo ? {valid_to: record.metadata.validTo} : {}),
    ...(record.metadata.lastReviewed ? {last_reviewed: record.metadata.lastReviewed} : {}),
    source_agent_client: record.metadata.sourceAgentClient,
    source_hash: sourceHash,
    relations: relations.map(relation => `${relation.type} ${relation.uri}`),
    evidence: [...(record.metadata.evidence ?? [])],
  };
  const relationLines = relations.map(relation => {
    const projected = projectedPathByUri.get(relation.uri);
    const target = projected
      ? `[[${projection.folder}/${withoutMarkdownExtension(projected)}]]`
      : `\`${relation.uri}\``;
    return `- **${relation.type.replaceAll('_', ' ')}:** ${target}  \n  \`${relation.uri}\``;
  });
  const rendered = [
    '---',
    yaml.dump(frontmatter, {lineWidth: 100, noRefs: true, sortKeys: false}).trimEnd(),
    '---',
    '',
    `<!-- ${PROJECTION_MANAGED_MARKER}:${projection.id}; do not edit -->`,
    '> [!warning] Generated view',
    '> Threadnote is authoritative. Changes to this file are not imported.',
    '',
    record.body,
    ...(relationLines.length > 0 ? ['', '## Relations', '', ...relationLines] : []),
    '',
  ].join('\n');
  const scrubbed = applyScrubber(rendered, {redact: true});
  if (scrubbed.blocker) {
    return undefined;
  }
  return {content: scrubbed.cleaned, contentHash: yield* sha256Hex(scrubbed.cleaned)};
});

const generatedProjectionFiles = Effect.fn('obsidian.generatedProjectionFiles')(function* (
  projection: ObsidianProjectionConfig,
) {
  const files = [
    {
      relativePath: 'README.md',
      content: [
        `<!-- ${PROJECTION_MANAGED_MARKER}:${projection.id}; do not edit -->`,
        '# Threadnote memory projection',
        '',
        'This folder is a generated, read-only view of authoritative Threadnote memory.',
        'Use Threadnote to create, replace, archive, or publish memories.',
        '',
      ].join('\n'),
    },
    ...projectionBaseDefinitions().map(view => ({
      relativePath: `Views/${view.filename}`,
      content: `# ${PROJECTION_MANAGED_MARKER}:${projection.id}\n${yaml.dump(view.definition, {
        lineWidth: 100,
        noRefs: true,
        sortKeys: false,
      })}`,
    })),
  ];
  return yield* Effect.forEach(files, file =>
    sha256Hex(file.content).pipe(
      Effect.map(contentHash => ({...file, contentHash, uri: undefined}) satisfies DesiredProjectionFile),
    ),
  );
});

function projectionBaseDefinitions(): ReadonlyArray<{
  readonly definition: Record<string, unknown>;
  readonly filename: string;
}> {
  const table = (filters: readonly string[]) => ({
    filters: {and: [...filters]},
    views: [
      {
        type: 'table',
        name: 'Threadnote',
        order: ['file.name', 'project', 'topic', 'status', 'updated_at'],
      },
    ],
  });
  return [
    {
      definition: table(['threadnote_generated == true', 'kind == "handoff"', 'status == "active"']),
      filename: 'Active Handoffs.base',
    },
    {
      definition: table(['threadnote_generated == true', 'kind == "durable"', 'status == "active"']),
      filename: 'Current Decisions.base',
    },
    {
      definition: table(['threadnote_generated == true', 'last_reviewed == null']),
      filename: 'Stale or Unreviewed.base',
    },
    {definition: table(['threadnote_generated == true', 'status == "superseded"']), filename: 'Contradictions.base'},
    {
      definition: table(['threadnote_generated == true', 'visibility == "shared"']),
      filename: 'Published and Shared.base',
    },
  ];
}

function projectionMemoryPath(record: MemoryRecord, memoryId: string): string {
  const project = uriSegment(record.metadata.project ?? 'unscoped');
  const topic = uriSegment(record.metadata.topic ?? uriBasename(record.uri));
  return `Memories/${project}/${record.metadata.kind}/${topic}--${memoryId.slice(-10)}.md`;
}

function memoryRelations(record: MemoryRecord): readonly MemoryRelation[] {
  const relations: MemoryRelation[] = [
    ...(record.metadata.relations ?? []),
    ...(record.metadata.references ?? []).map(uri => ({type: 'references' as const, uri})),
    ...(record.metadata.evidence ?? [])
      .filter(value => value.startsWith('threadnote://'))
      .map(uri => ({type: 'evidence_for' as const, uri})),
    ...(record.metadata.supersedes ? [{type: 'supersedes' as const, uri: record.metadata.supersedes}] : []),
  ];
  const seen = new Set<string>();
  return relations.filter(relation => {
    const key = `${relation.type}\n${relation.uri}`;
    if (seen.has(key)) {
      return false;
    }
    seen.add(key);
    return true;
  });
}

