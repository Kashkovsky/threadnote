export const runObsidianProjectionAdd = Effect.fn('obsidian.projectionAdd')(function* (
  config: RuntimeConfig,
  options: ObsidianProjectionAddOptions,
) {
  const id = normalizeIdentifier(options.id, 'projection id');
  const vault = yield* canonicalDirectory(options.vault, 'Obsidian vault');
  const folder = normalizeProjectionFolder(options.folder);
  const current = yield* readObsidianConfiguration(config);
  const existing = current.projections.find(projection => projection.id === id);
  const projection: ObsidianProjectionConfig = {
    enabled: true,
    folder,
    id,
    includeShared: options.includeShared !== false,
    kinds: options.kinds?.length ? [...new Set(options.kinds)] : ['durable', 'handoff'],
    selectedUris: existing?.selectedUris ?? [],
    statuses: options.statuses?.length ? [...new Set(options.statuses)] : ['active'],
    type: 'obsidian',
    vault,
  };
  const projectionExclude = `${folder}/**`;
  const sources = current.sources.map(source =>
    source.vault === vault && !source.exclude.includes(projectionExclude)
      ? {...source, exclude: [...source.exclude, projectionExclude]}
      : source,
  );
  const next = upsertObsidianProjection({...current, sources}, projection);
  if (options.apply !== true) {
    yield* Console.log(`Would configure Obsidian projection "${id}":`);
    yield* Console.log(projectionSummary(projection));
    if (sources.some((source, index) => source !== current.sources[index])) {
      yield* Console.log(`Would exclude ${projectionExclude} from matching sources in the same vault.`);
    }
    yield* Console.log('Re-run with --apply to write the configuration.');
    return;
  }
  const path = yield* writeObsidianConfiguration(config, next);
  yield* Console.log(`Configured Obsidian projection "${id}" in ${path}.`);
});

