export type ObsidianProjectionAction = 'add' | 'drift' | 'remove' | 'skip' | 'unchanged' | 'update';

export interface ObsidianProjectionEntry {
  readonly action: ObsidianProjectionAction;
  readonly detail?: string;
  readonly relativePath: string;
  readonly uri?: string;
}

interface ObsidianProjectionFileState {
  readonly contentHash: string;
  readonly uri?: string;
}

export interface ObsidianProjectionState {
  readonly files: Readonly<Record<string, ObsidianProjectionFileState>>;
  readonly projectionId: string;
  readonly syncedAt?: string;
  readonly version: 1;
}

interface DesiredProjectionFile {
  readonly content: string;
  readonly contentHash: string;
  readonly relativePath: string;
  readonly uri?: string;
}

interface ProjectionPlan {
  readonly desired: ReadonlyMap<string, DesiredProjectionFile>;
  readonly entries: readonly ObsidianProjectionEntry[];
  readonly projection: ObsidianProjectionConfig;
  readonly state: ObsidianProjectionState;
}

