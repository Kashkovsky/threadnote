export const readProjectionState = Effect.fn('obsidian.readProjectionState')(function* (
  path: string,
  projectionId: string,
) {
  const fs = yield* FileSystem.FileSystem;
  if (!(yield* fs.exists(path))) {
    return emptyProjectionState(projectionId);
  }
  const raw = yield* fs.readFileString(path);
  return yield* Effect.try({
    try: () => parseProjectionState(JSON.parse(raw), projectionId),
    catch: cause => (cause instanceof Error ? cause : new Error(String(cause))),
  });
});

const writeProjectionState = Effect.fn('obsidian.writeProjectionState')(function* (
  path: string,
  state: ObsidianProjectionState,
) {
  const fs = yield* FileSystem.FileSystem;
  const pathService = yield* Path.Path;
  const crypto = yield* Crypto.Crypto;
  yield* fs.makeDirectory(pathService.dirname(path), {recursive: true});
  const temporaryPath = `${path}.${yield* crypto.randomUUIDv4}.tmp`;
  yield* fs.writeFileString(temporaryPath, `${JSON.stringify(state, undefined, 2)}\n`, {
    mode: PROJECTION_PRIVATE_FILE_MODE,
  });
  yield* fs
    .rename(temporaryPath, path)
    .pipe(Effect.ensuring(fs.remove(temporaryPath, {force: true}).pipe(Effect.catch(() => Effect.void))));
  yield* fs.chmod(path, PROJECTION_PRIVATE_FILE_MODE);
});

function parseProjectionState(value: unknown, projectionId: string): ObsidianProjectionState {
  if (
    typeof value !== 'object' ||
    value === null ||
    !('version' in value) ||
    value.version !== PROJECTION_STATE_VERSION ||
    !('projectionId' in value) ||
    value.projectionId !== projectionId ||
    !('files' in value) ||
    typeof value.files !== 'object' ||
    value.files === null
  ) {
    throw new Error(`Invalid Obsidian projection state for "${projectionId}".`);
  }
  const files: Record<string, ObsidianProjectionFileState> = {};
  for (const [relativePath, entry] of Object.entries(value.files)) {
    assertSafeProjectionRelativePath(relativePath);
    if (
      typeof entry !== 'object' ||
      entry === null ||
      !('contentHash' in entry) ||
      typeof entry.contentHash !== 'string'
    ) {
      throw new Error(`Invalid Obsidian projection state entry "${relativePath}".`);
    }
    files[relativePath] = {
      contentHash: entry.contentHash,
      uri: 'uri' in entry && typeof entry.uri === 'string' ? entry.uri : undefined,
    };
  }
  return {
    files,
    projectionId,
    syncedAt: 'syncedAt' in value && typeof value.syncedAt === 'string' ? value.syncedAt : undefined,
    version: PROJECTION_STATE_VERSION,
  };
}

function emptyProjectionState(projectionId: string): ObsidianProjectionState {
  return {files: {}, projectionId, version: PROJECTION_STATE_VERSION};
}

const writeProjectionFile = Effect.fn('obsidian.writeProjectionFile')(function* (
  root: string,
  file: DesiredProjectionFile,
) {
  const fs = yield* FileSystem.FileSystem;
  const pathService = yield* Path.Path;
  const crypto = yield* Crypto.Crypto;
  const target = yield* safeProjectionTarget(root, file.relativePath);
  yield* fs.makeDirectory(pathService.dirname(target), {recursive: true});
  const temporaryPath = `${target}.${yield* crypto.randomUUIDv4}.tmp`;
  yield* fs.writeFileString(temporaryPath, file.content, {mode: PROJECTION_NOTE_FILE_MODE});
  yield* fs
    .rename(temporaryPath, target)
    .pipe(Effect.ensuring(fs.remove(temporaryPath, {force: true}).pipe(Effect.catch(() => Effect.void))));
  yield* fs.chmod(target, PROJECTION_NOTE_FILE_MODE);
});

const safeProjectionTarget = Effect.fn('obsidian.safeProjectionTarget')(function* (root: string, relativePath: string) {
  assertSafeProjectionRelativePath(relativePath);
  const pathService = yield* Path.Path;
  const target = pathService.resolve(root, ...relativePath.split('/'));
  const relative = pathService.relative(pathService.resolve(root), target);
  if (relative === '..' || relative.startsWith(`..${pathService.sep}`) || pathService.isAbsolute(relative)) {
    return yield* Effect.fail(new Error(`Projection path escapes its managed folder: ${relativePath}`));
  }
  return target;
});

function assertSafeProjectionRelativePath(relativePath: string): void {
  const normalized = toPosixPath(relativePath);
  if (
    normalized.length === 0 ||
    normalized.startsWith('/') ||
    normalized.split('/').some(segment => segment === '' || segment === '.' || segment === '..')
  ) {
    throw new Error(`Unsafe projection state path: ${relativePath}`);
  }
}

function fileContentHash(
  fs: FileSystem.FileSystem,
  path: string,
): Effect.Effect<string | undefined, never, Crypto.Crypto> {
  return fs.readFile(path).pipe(Effect.flatMap(sha256Hex), Effect.option, Effect.map(Option.getOrUndefined));
}

const removeEmptyProjectionDirectories = Effect.fn('obsidian.removeEmptyProjectionDirectories')(function* (
  root: string,
) {
  const fs = yield* FileSystem.FileSystem;
  const removeIfEmpty = (path: string): Effect.Effect<void, never> =>
    Effect.gen(function* () {
      const names = yield* fs.readDirectory(path).pipe(Effect.catch(() => Effect.succeed([])));
      if (names.length === 0) {
        yield* fs.remove(path, {force: true}).pipe(Effect.catch(() => Effect.void));
      }
    });
  yield* removeIfEmpty(root);
});

const canonicalDirectory = Effect.fn('obsidian.projectionCanonicalDirectory')(function* (value: string, label: string) {
  const fs = yield* FileSystem.FileSystem;
  const expanded = yield* expandPath(value);
  if (!(yield* isDirectory(expanded))) {
    return yield* Effect.fail(new Error(`${label} is not a directory: ${expanded}`));
  }
  return yield* fs.realPath(expanded);
});

function normalizeProjectionFolder(value: string): string {
  const normalized = toPosixPath(value).replace(/^\/+|\/+$/g, '');
  if (
    normalized.length === 0 ||
    normalized.split('/').some(segment => segment === '' || segment === '.' || segment === '..')
  ) {
    throw new Error('Projection folder must be a safe vault-relative path.');
  }
  return normalized;
}

function normalizeIdentifier(value: string, label: string): string {
  const normalized = value.trim().toLowerCase();
  if (!/^[a-z0-9][a-z0-9._-]*$/.test(normalized)) {
    throw new Error(`${label} must contain only lowercase letters, digits, dots, underscores, and hyphens.`);
  }
  return normalized;
}

function projectionSummary(projection: ObsidianProjectionConfig): string {
  return [
    `${projection.id} · ${projection.enabled ? 'enabled' : 'disabled'} · ${projection.vault}/${projection.folder}`,
    `  selected memories: ${projection.selectedUris?.length ?? 'all matching (legacy)'}`,
    `  kinds: ${projection.kinds.join(', ')}`,
    `  statuses: ${projection.statuses.join(', ')}`,
    `  shared: ${projection.includeShared ? 'included' : 'excluded'}`,
  ].join('\n');
}

const printProjectionPlan = Effect.fn('obsidian.printProjectionPlan')(function* (plan: ProjectionPlan) {
  if (plan.entries.length === 0) {
    yield* Console.log(`Obsidian projection "${plan.projection.id}" has no files to change.`);
    return;
  }
  for (const entry of plan.entries) {
    yield* Console.log(
      `${entry.action.toUpperCase().padEnd(9)} ${entry.relativePath}${entry.detail ? ` (${entry.detail})` : ''}`,
    );
  }
  const counts = projectionCounts(plan.entries);
  yield* Console.log(
    `Projection: ${counts.add} add, ${counts.update} update, ${counts.remove} remove, ` +
      `${counts.unchanged} unchanged, ${counts.drift} drift, ${counts.skip} skipped.`,
  );
});

function projectionCounts(entries: readonly ObsidianProjectionEntry[]): Record<ObsidianProjectionAction, number> {
  const counts: Record<ObsidianProjectionAction, number> = {
    add: 0,
    drift: 0,
    remove: 0,
    skip: 0,
    unchanged: 0,
    update: 0,
  };
  for (const entry of entries) {
    counts[entry.action] += 1;
  }
  return counts;
}

function projectionActionRank(action: ObsidianProjectionAction): number {
  return {add: 0, update: 1, remove: 2, drift: 3, skip: 4, unchanged: 5}[action];
}

function uriBasename(uri: string): string {
  const withoutAnchor = uri.replace(/#.*$/, '').replace(/\/+$/, '');
  return withoutAnchor.slice(withoutAnchor.lastIndexOf('/') + 1).replace(/\.md$/i, '');
}

function normalizeProjectionMemoryUris(
  config: Pick<RuntimeConfig, 'user'>,
  values: readonly string[],
): readonly string[] {
  if (values.length === 0) {
    throw new Error('Provide at least one Threadnote memory URI with --uri.');
  }
  const expectedUser = uriSegment(config.user);
  return [...new Set(values.map(value => canonicalProjectionMemoryUri(value, expectedUser)))].sort((left, right) =>
    left.localeCompare(right),
  );
}

function canonicalProjectionMemoryUri(value: string, expectedUser: string): string {
  const parsed = parseResourceId(value);
  if (parsed.anchor) {
    throw new Error(`Obsidian projections require whole-memory URIs without anchors: ${value}`);
  }
  const canonical = resourceIdWithoutAnchor(parsed);
  if (
    canonical.namespace !== 'user' ||
    canonical.segments[0] !== expectedUser ||
    canonical.segments[1] !== 'memories' ||
    canonical.segments.length < 3 ||
    !canonical.segments.at(-1)?.toLowerCase().endsWith('.md')
  ) {
    throw new Error(`Obsidian projections accept only current-user Threadnote memory URIs: ${value}`);
  }
  return canonical.canonicalUri;
}

