import {expect, it} from '@effect/vitest';
import {Effect, FileSystem, Path} from 'effect';
import {describe} from 'vitest';
import {captureConsole} from '../../src/effect/console.js';
import {CommandExecutor} from '../../src/effect/command.js';
import {ApplicationLayer} from '../../src/effect/runtime.js';
import {SystemInfo} from '../../src/effect/system.js';
import {
  applyLegacyInstallationCleanup,
  planLegacyInstallationCleanup,
} from '../../src/migration/legacy-installations.js';

describe('legacy installation cleanup', () => {
  it.effect('removes verified Threadnote 3 and OpenViking tools while preserving the legacy home', () =>
    Effect.scoped(
      Effect.gen(function* () {
        const fs = yield* FileSystem.FileSystem;
        const path = yield* Path.Path;
        const baseSystem = yield* SystemInfo;
        const root = yield* fs.makeTempDirectoryScoped({prefix: 'threadnote-legacy-installations-'});
        const home = path.join(root, 'home');
        const bin = path.join(root, 'bin');
        const npmPrefix = path.join(root, 'npm-prefix');
        const npm = path.join(npmPrefix, 'bin', 'npm');
        const legacyCli = path.join(npmPrefix, 'bin', 'threadnote');
        const packageRoot = path.join(npmPrefix, 'lib', 'node_modules', 'threadnote');
        const uv = path.join(bin, 'uv');
        const pipx = path.join(bin, 'pipx');
        const python = path.join(bin, 'python3');
        const launcherRoot = path.join(home, '.local', 'bin');
        const launcher = path.join(launcherRoot, 'threadnote');
        const legacyHome = path.join(home, '.openviking');
        const launchAgent = path.join(home, 'Library', 'LaunchAgents', 'io.threadnote.openviking.plist');
        yield* fs.makeDirectory(path.dirname(npm), {recursive: true});
        yield* fs.makeDirectory(packageRoot, {recursive: true});
        yield* fs.makeDirectory(bin);
        yield* fs.makeDirectory(launcherRoot, {recursive: true});
        yield* fs.makeDirectory(path.join(legacyHome, 'threadnote'), {recursive: true});
        yield* fs.makeDirectory(path.dirname(launchAgent), {recursive: true});
        yield* fs.writeFileString(path.join(packageRoot, 'package.json'), '{"name":"threadnote","version":"3.0.3"}\n');
        for (const executable of [npm, legacyCli, uv, pipx, python]) {
          yield* fs.writeFileString(executable, '#!/bin/sh\nexit 0\n', {mode: 0o755});
          yield* fs.chmod(executable, 0o755);
        }
        yield* fs.writeFileString(
          launcher,
          [
            '#!/usr/bin/env bash',
            '# Generated by threadnote',
            `THREADNOTE_ROOT=${packageRoot}`,
            'exec node "$THREADNOTE_ROOT/bin/threadnote.cjs" "$@"',
          ].join('\n'),
          {mode: 0o755},
        );
        yield* fs.writeFileString(launchAgent, '<plist><dict/></plist>\n');

        const calls: string[] = [];
        const commandExecutor = CommandExecutor.of({
          execute: (executable, args) =>
            Effect.sync(() => {
              calls.push([executable, ...args].join(' '));
              if (executable === npm && args[0] === 'ls') {
                return {
                  exitCode: 0,
                  stderr: '',
                  stdout: '{"dependencies":{"threadnote":{"version":"3.0.3"}}}\n',
                };
              }
              if (executable === npm && args[0] === 'prefix') {
                return {exitCode: 0, stderr: '', stdout: `${npmPrefix}\n`};
              }
              if (executable === uv && args[0] === 'tool' && args[1] === 'list') {
                return {exitCode: 0, stderr: '', stdout: 'openviking v0.4.10\n- ov\n'};
              }
              if (executable === pipx && args[0] === 'list') {
                return {exitCode: 0, stderr: '', stdout: '{"venvs":{}}\n'};
              }
              if (executable === python && args.includes('show')) {
                return {exitCode: 1, stderr: 'not installed', stdout: ''};
              }
              return {exitCode: 0, stderr: '', stdout: ''};
            }),
          executeStreaming: () => Effect.die(new Error('Unexpected streaming command')),
        });
        const testSystem = SystemInfo.of({
          ...baseSystem,
          environment: () => ({
            PATH: bin,
            THREADNOTE_BIN_DIR: launcherRoot,
          }),
          homeDirectory: home,
          pathDelimiter: ':',
          platform: 'darwin',
          userId: 501,
        });

        const result = yield* captureConsole(
          Effect.gen(function* () {
            const plan = yield* planLegacyInstallationCleanup();
            expect(plan.npm).toHaveLength(1);
            expect(plan.openViking).toHaveLength(1);
            yield* applyLegacyInstallationCleanup(plan, false);
          }),
        ).pipe(Effect.provideService(CommandExecutor, commandExecutor), Effect.provideService(SystemInfo, testSystem));

        expect(calls).toContain(`${legacyCli} stop`);
        expect(calls).toContain(`${npm} uninstall --global threadnote`);
        expect(calls).toContain(`${uv} tool uninstall openviking`);
        expect(calls).toContain('launchctl bootout gui/501/io.threadnote.openviking');
        expect(yield* fs.exists(launchAgent)).toBe(false);
        expect(yield* fs.exists(legacyHome)).toBe(true);
        expect(result.output).toContain(`Preserved legacy memories and rollback data: ${legacyHome}`);
      }),
    ).pipe(Effect.provide(ApplicationLayer)),
  );

  it.effect('leaves unrelated OpenViking installations untouched without Threadnote ownership evidence', () =>
    Effect.scoped(
      Effect.gen(function* () {
        const fs = yield* FileSystem.FileSystem;
        const path = yield* Path.Path;
        const baseSystem = yield* SystemInfo;
        const root = yield* fs.makeTempDirectoryScoped({prefix: 'threadnote-unowned-openviking-'});
        const home = path.join(root, 'home');
        const bin = path.join(root, 'bin');
        const npm = path.join(bin, 'npm');
        const uv = path.join(bin, 'uv');
        yield* fs.makeDirectory(home);
        yield* fs.makeDirectory(bin);
        for (const executable of [npm, uv]) {
          yield* fs.writeFileString(executable, '#!/bin/sh\nexit 0\n', {mode: 0o755});
          yield* fs.chmod(executable, 0o755);
        }

        const calls: string[] = [];
        const commandExecutor = CommandExecutor.of({
          execute: (executable, args) =>
            Effect.sync(() => {
              calls.push([executable, ...args].join(' '));
              if (executable === npm && args[0] === 'ls') {
                return {
                  exitCode: 0,
                  stderr: '',
                  stdout: '{"dependencies":{}}\n',
                };
              }
              if (executable === npm && args[0] === 'prefix') {
                return {exitCode: 0, stderr: '', stdout: `${root}\n`};
              }
              if (executable === uv && args[0] === 'tool' && args[1] === 'list') {
                return {exitCode: 0, stderr: '', stdout: 'openviking v0.4.10\n- ov\n'};
              }
              return {exitCode: 0, stderr: '', stdout: ''};
            }),
          executeStreaming: () => Effect.die(new Error('Unexpected streaming command')),
        });
        const testSystem = SystemInfo.of({
          ...baseSystem,
          environment: () => ({PATH: bin, THREADNOTE_BIN_DIR: path.join(root, 'launcher')}),
          homeDirectory: home,
          pathDelimiter: ':',
          platform: 'darwin',
          userId: 501,
        });

        const plan = yield* planLegacyInstallationCleanup().pipe(
          Effect.provideService(CommandExecutor, commandExecutor),
          Effect.provideService(SystemInfo, testSystem),
        );

        expect(plan.npm).toEqual([]);
        expect(plan.openViking).toEqual([]);
        expect(calls.some(call => call.includes('uninstall'))).toBe(false);
        expect(calls.some(call => call.includes('tool list'))).toBe(false);
      }),
    ).pipe(Effect.provide(ApplicationLayer)),
  );
});
